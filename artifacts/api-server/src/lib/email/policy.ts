/** المسارات التي يدخلها قطاع. قطاعٌ خارج الاستهداف يُرجع قائمةً فارغة. */
export function tracksFor(sector: string | null | undefined): Track[] {
  if (!sector) return [];
  return (Object.keys(TARGETS) as Track[]).filter((t) => TARGETS[t].includes(sector));
}

export const isTargeted = (sector: string | null | undefined): boolean => tracksFor(sector).length > 0;

export function anglesFor(track: Track, sector: string): Angle[] {
  return ANGLES[track]?.[sector] ?? ANGLES[track]?.[FAMILY[sector] ?? ""] ?? [];
}

/**
 * زاوية الموجة القادمة: الدور على ما لم يُستعمل، مع تخطّي ما حكم عليه
 * المحلّل بالفشل — حتى لا تبقى إلا واحدة فتُستعمل. `used` هي زوايا
 * موجات هذا (المسار، القطاع) السابقة، بالترتيب.
 */
export function nextAngle(track: Track, sector: string, used: string[], avoid: string[] = []): Angle | null {
  const all = anglesFor(track, sector);
  if (!all.length) return null;
  const ok = all.filter((a) => !avoid.includes(a.id));
  const pool = ok.length ? ok : all;
  // الأقل استعمالاً أولاً، وعند التعادل الأبعد عهداً.
  const count = (id: string) => used.filter((u) => u === id).length;
  const last = (id: string) => used.lastIndexOf(id);
  return [...pool].sort((a, b) => count(a.id) - count(b.id) || last(a.id) - last(b.id))[0]!;
}

export function trackOfAngle(id: string | null | undefined): Track | null {
  if (!id) return null;
  for (const t of Object.keys(ANGLES) as Track[]) {
    for (const s of Object.keys(ANGLES[t])) if (ANGLES[t][s]!.some((a) => a.id === id)) return t;
  }
  return null;
}

export function angleById(id: string | null | undefined): (Angle & { track: Track; sector: string }) | null {
  if (!id) return null;
  for (const t of Object.keys(ANGLES) as Track[]) {
    for (const s of Object.keys(ANGLES[t])) {
      const a = ANGLES[t][s]!.find((x) => x.id === id);
      if (a) return { ...a, track: t, sector: s };
    }
  }
  return null;
}

// ── النسبة ────────────────────────────────────────────────────────
export interface MixState { aml: number; services: number }

export function mixShare(s: MixState): Record<Track, number> {
  const total = s.aml + s.services;
  return total ? { aml: s.aml / total, services: s.services / total } : { aml: 0, services: 0 };
}

/**
 * كم يجوز لمسار الخدمات أن يأخذ الآن.
 *
 * النسبة سقفٌ على الخدمات لا قيدٌ على AML: الخدمات لا تتجاوز خُمس
 * الحجم، وAML يأخذ الباقي كله. ولو قُيّد AML بالنسبة لتوقّف الإرسال
 * كله يوم لا يكون للخدمات جمهور — وقوائم اليوم عقاراتٌ كلها تقريباً.
 *
 * واستثناءٌ واحد: إن لم يبقَ لـAML جمهورٌ أصلاً رُفع السقف، فنسبةٌ
 * تُوقف الإرسال كله لم يقصدها أحد. ويُقال ذلك في التقرير.
 */
export function servicesAllowance(s: MixState, opts: { amlHasAudience: boolean }): { allowed: number; lifted: boolean } {
  if (!opts.amlHasAudience) return { allowed: Number.MAX_SAFE_INTEGER, lifted: true };
  // services ≤ 20٪ من المجموع  ⇔  services ≤ aml × (0.2 / 0.8)
  const cap = Math.floor(s.aml * (MIX.services / MIX.aml));
  return { allowed: Math.max(0, cap - s.services), lifted: false };
}

/**
 * مسار الموجة لقطاعٍ بعينه. القطاع الذي في المسارين (العقارات) يذهب
 * للخدمات حين يتّسع لها سقفها، وإلا فلـAML.
 */
export function chooseTrack(sector: string, s: MixState, opts: { amlHasAudience: boolean; minWave: number }): { track: Track; take: number | null; why: string } | null {
  const tracks = tracksFor(sector);
  if (!tracks.length) return null;
  const al = servicesAllowance(s, opts);
  const svcOk = al.allowed >= opts.minWave;
  if (tracks.includes("services") && svcOk) {
    return { track: "services", take: al.lifted ? null : al.allowed,
      why: al.lifted ? "لا جمهور باقٍ لـAML — رُفع سقف الخدمات" : `الخدمات دون حصّتها: يتّسع لها ${al.allowed}` };
  }
  if (tracks.includes("aml")) return { track: "aml", take: null, why: "AML هو المسار الأول، والخدمات عند سقفها أو ليست لهذا القطاع" };
  return null;   // قطاع خدماتٍ فقط، والسقف ممتلئ: ينتظر
}

