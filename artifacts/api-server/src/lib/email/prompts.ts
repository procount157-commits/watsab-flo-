/** خطةُ هذه النيّة وحدها. */
export function playFor(intent: EmailIntent | null | undefined): string {
  const p = PLAYS[intent ?? "unclear"] ?? PLAYS.unclear;
  return p.join("\n");
}

/**
 * تعليمات كتابة ردٍّ على رسالةٍ وصلت: الصنعة، ثم خطةُ نيّته، ثم
 * المحرّمات. الخيط يُضاف من `threadBrief` في موضع الاستدعاء.
 */
export function replyInstructions(intent: EmailIntent | null | undefined, opts: { hasHistory: boolean; silent: boolean } = { hasHistory: false, silent: false }): string {
  return [
    WRITING_DOCTRINE,
    "",
    playFor(intent),
    opts.hasHistory ? "• راسلته قبل اليوم: لا تُعرّف نفسك من جديد، ولا تُعِد ما قلته، وأشِر إلى ما تبادلتماه إشارةً دقيقة لا عامة." : "",
    opts.silent ? "• لم يُفتح شيءٌ من رسائلنا السابقة إليه — فلا تبنِ على أنه قرأها." : "",
    "",
    NEVER,
  ].filter(Boolean).join("\n");
}

/** تعليمات متابعةٍ لمن لم يردّ. تُستدعى من درجات التتابع والمهام. */
export function followUpInstructions(opts: { touch: number; silent: boolean; lastIntent?: EmailIntent | null }): string {
  return [
    WRITING_DOCTRINE,
    "",
    FOLLOWUP_DOCTRINE,
    `هذه اللمسة رقم ${opts.touch} مع هذه الشركة.`,
    opts.silent ? "ولم يُفتح شيءٌ من كل ما أُرسل إليها: غيّر الزاوية والعنوان تماماً — لا تُعِد صياغة الرسالة نفسها." : "",
    opts.lastIntent ? playFor(opts.lastIntent) : "",
    opts.touch >= 4 ? "هذه لمسةٌ متأخرة: اجعلها الأقصر في الخيط — أربع جُمل على الأكثر — واجعلها سؤالاً واحداً يُجاب بنعم أو لا." : "",
    "",
    NEVER,
  ].filter(Boolean).join("\n");
}

