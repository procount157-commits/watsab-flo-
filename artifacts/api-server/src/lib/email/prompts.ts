//   ٢ · خطةُ النيّة الواحدة. لا تُحمَّل الإحدى عشرة خطة في كل رد —
//       تُنتقى واحدة. المزوّد المجاني يعطي ٨٠٠٠ رمزاً في الدقيقة لكل
//       شيء: التعليمات والمعرفة والرد، وما يُحشى يُضعِف ما يُقرأ.
//   ٣ · لا رقم من عند النموذج. الأرقام تأتي من معرفة صاحب العمل أو لا
//       تأتي. غرامةٌ مُختلقة في رسالةٍ من مكتب محاسبة تُفقده العميل
