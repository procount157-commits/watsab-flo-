/** نصّ المعيار في ملف الموظف. Pure. */
export function standardText(): string {
  const s = PERSUASION_STANDARD;
  return [
    `${s.title}:`,
    ...s.principles.map((p) => `- ${p}`),
    "التمييز:",
    ...s.classify.map((p) => `- ${p}`),
    "معالجة الاعتراضات:",
    ...Object.entries(s.objections).map(([k, v]) => `- ${OBJECTION_TITLES[k as ObjectionType]}: ${v}`),
    `التوقف: ${s.stop}`,
    "ممنوع:",
    ...s.prohibited.map((p) => `- ${p}`),
  ].join("\n");
}

