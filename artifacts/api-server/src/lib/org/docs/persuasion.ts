/** أي تطبيقٍ يحكم هذا الموظف. null: ليس دور بيع أو تواصل. Pure. */
export function persuasionRoleOf(employeeKey: string): PersuasionRole | null {
  const k = employeeKey;
  if (k === "executive.chief") return "sales_director";
  if (k === "whatsapp.sales" || k === "shared.proposals") return "sales_specialist";
  if (k === "whatsapp.support") return "customer_success";
  if (k === "email.strategist" || k === "email.retarget") return "campaign_strategist";
  if (["email.copywriter", "email.followup", "email.creator", "target_accounts.writer", "whatsapp.campaigns", "whatsapp.followup"].includes(k)) return "copywriter";
  if (/^(instagram|tiktok)\.(writer|prospector|followup|inviter)$/.test(k)) return "copywriter";
  if (/^(instagram|tiktok)\.qualify$/.test(k) || k === "shared.collector") return "lead_qualification";
  if (k === "email.replies" || /^(instagram|tiktok)\.dm$/.test(k)) return "reply_dm";
  if (["executive.ceo", "email.director"].includes(k) || /^(instagram|tiktok)\.manager$/.test(k)) return "manager";
  return null;
}

