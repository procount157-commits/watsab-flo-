import assert from "node:assert/strict";
import { asksToStop, STOP_MONTHS } from "../opt-out";
import { GUARD_RULES, phoneKey } from "../wa-send-guard";
import { DAILY_LIMIT_MAX } from "../daily-limit";
let n = 0; const ok = (c: boolean, m: string) => { assert.ok(c, m); n++; };
ok(GUARD_RULES.dailyCap === 200 && DAILY_LIMIT_MAX === 200, "200 a day, from both places");
ok(STOP_MONTHS === 6, "the stop button blocks six months");
for (const t of ["إيقاف", "الغاء الاشتراك", "stop", "STOP!!", "شيلوا رقمي لو سمحت", "لا ترسلوا لي", "ما ابي رسايل 🙏", "احذف رقمي", "Unsubscribe."]) ok(asksToStop(t), `«${t}» asks to stop`);
for (const t of ["الغاء الطلب رقم ٥٤٣ لو سمحت وارسلوا البديل بكرة الصبح مع التوصيل", "كم سعر الطقم؟", "تمام شكرا", "ابي اوقف الطلب واغير المقاس"]) ok(!asksToStop(t), `«${t}» does not`);
ok(phoneKey("971501071611") === phoneKey("0501071611") && phoneKey("+971 50 107 1611") === phoneKey("971501071611:0"), "the blacklist knows the person, not the spelling");
console.log(`wa-controls: ${n}/${n} ✅`);
