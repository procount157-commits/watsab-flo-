/** عباراتٌ تُسقط المتابعة آلياً — فحصٌ بالكود لا بوعد النموذج. */
const BANNED = /(أتابع معك|اتابع معك|للتذكير|هل وصلتك رسالتي|هل وصلتكم رسالتي|لم أسمع منك|لم اسمع منك|أردت فقط|اردت فقط|آسف على الإزعاج|اسف على الازعاج|نأسف على الإزعاج|كما ذكرت سابقا|كما ذكرنا سابقا|لاحظت أنك لم ترد|لاحظت انك لم ترد|just checking in|just following up|following up on my|touching base|any updates?\b|circling back|bumping this|sorry to bother)/i;

/** ما في المتابعة مما يُمنع — قائمةٌ فارغة تعني أنها تمرّ. صِرفة. */
export function followupIssues(text: string, opts: { last?: boolean; previous?: string | null } = {}): string[] {
  const t = text.replace(/[ً-ٰٟ]/g, "");
  const out: string[] = [];
  const hit = BANNED.exec(t);
  if (hit) out.push(`عبارة تذكير تُغلق المحادثة: «${hit[0]}»`);
  const questions = (t.match(/[?؟]/g) ?? []).length;
  if (questions > 1) out.push(`${questions} أسئلة — المتابعة طلبٌ واحد`);
  if (opts.last && questions > 0) out.push("المتابعة الأخيرة وداع — بلا سؤال");
  if (opts.previous && t.trim().length > opts.previous.trim().length * 1.3 && t.length > 220) out.push("أطول من الرسالة التي سكت بعدها — المتابعة أقصر");
  return out;
}
