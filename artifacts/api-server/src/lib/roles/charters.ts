// ── Who does what: the charter of every role ─────────────────────
// Forty employees, and the owner could not tell what most of them were for —
// nor, from their prompts, could they. A persona says who someone is ("صبور،
// لا يُلحّ"); it does not say what they are responsible for, when they act,
// what they hand over and to whom, or how anyone would know they did it well.
// A weak model given a character and no job improvises a job, and the
// improvised one is always the same: a polite, generic message.
//
// So every role has a charter, written once here and rendered into its
// instructions right after its persona:
//
//   department → mission in one sentence → when it acts → what it receives →
//   what it delivers → how it is measured → who it hands to, and when →
//   what is not its job
//
// The social roles are the same on every platform and are keyed by job
// (ig_writer and tt_writer are both "writer"). The persona stays the owner's
// to edit; the charter is the job description, and is the same for every
// account.

