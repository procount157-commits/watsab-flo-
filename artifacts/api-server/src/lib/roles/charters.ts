/** The charter for a role, the social ones by their job. */
export function charterOf(role: string): Charter | null {
  if (CORE[role]) return CORE[role]!;
  if (EMAIL[role]) return EMAIL[role]!;
  const m = /^(ig|tt|li|fb|x)_(.+)$/.exec(role);
  if (m && SOCIAL[m[2]!]) return SOCIAL[m[2]!]!;
  return null;
}

/** The charter as it is read by the one who holds it. */
export function charterBlock(role: string): string {
  const c = charterOf(role);
  if (!c) return "";
  return [
    "═══ دورك في الفريق ═══",
    `القسم: ${c.department}`,
    `مهمتك: ${c.mission}`,
    `متى تعمل: ${c.when}`,
    `ما يصلك: ${c.receives}`,
    `ما تسلّمه: ${c.delivers}`,
    `تُقاس بـ: ${c.measured}`,
    c.handsTo ? `تسلّم إلى: ${c.handsTo}` : "",
    c.notMine ? `ليس من شغلك: ${c.notMine}` : "",
  ].filter(Boolean).join("\n");
}

